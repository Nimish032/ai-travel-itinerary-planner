"""Offline PDF export for saved itineraries."""

from __future__ import annotations

import io
import re
from pathlib import Path
from typing import List

from core.models import Itinerary, SavedTrip


def _safe_text(value: object) -> str:
    text = str(value or "")
    return re.sub(r"[^\x09\x0A\x0D\x20-\x7E]", "", text)


def _font_name() -> str:
    try:
        from reportlab.pdfbase import pdfmetrics
        from reportlab.pdfbase.ttfonts import TTFont

        candidates = [
            Path("C:/Windows/Fonts/DejaVuSans.ttf"),
            Path("C:/Windows/Fonts/arial.ttf"),
        ]
        for path in candidates:
            if path.exists():
                name = "TravelPlannerFont"
                pdfmetrics.registerFont(TTFont(name, str(path)))
                return name
    except (ImportError, OSError, TypeError):
        pass
    return "Helvetica"


def _footer(canvas, document) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColorRGB(0.35, 0.35, 0.35)
    canvas.drawString(42, 24, "Generated by Personalized Travel Itinerary Planner")
    canvas.drawRightString(553, 24, f"Page {document.page}")
    canvas.restoreState()


def _activity_rows(itinerary: Itinerary) -> List[List[str]]:
    rows: List[List[str]] = [["Time", "Activity", "Area", "Cost", "Tips"]]
    for day in itinerary.days:
        for slot in day.slots:
            for activity in slot.activities:
                rows.append([
                    _safe_text(activity.start_time or slot.slot_type),
                    _safe_text(activity.name),
                    _safe_text(activity.area),
                    f"{_safe_text(activity.currency_local)} {activity.cost_local:,.0f}",
                    _safe_text(activity.tips),
                ])
    return rows


def generate_pdf(trip: SavedTrip) -> bytes:
    """Return a complete A4 PDF as bytes for download."""

    try:
        from reportlab.lib import colors
        from reportlab.lib.enums import TA_CENTER
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (
            Flowable, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
        )
    except ImportError as exc:
        raise RuntimeError("ReportLab is required to export a PDF.") from exc

    font = _font_name()
    buffer = io.BytesIO()
    document = SimpleDocTemplate(
        buffer, pagesize=A4, rightMargin=15 * mm, leftMargin=15 * mm,
        topMargin=15 * mm, bottomMargin=15 * mm,
        title=_safe_text(trip.title),
    )
    styles = getSampleStyleSheet()
    title = ParagraphStyle("TravelTitle", parent=styles["Title"], fontName=font,
                           fontSize=26, leading=32, textColor=colors.HexColor("#0B1F33"),
                           alignment=TA_CENTER, spaceAfter=14)
    heading = ParagraphStyle("TravelHeading", parent=styles["Heading2"], fontName=font,
                             textColor=colors.HexColor("#0F766E"), spaceBefore=10)
    body = ParagraphStyle("TravelBody", parent=styles["BodyText"], fontName=font,
                          fontSize=9, leading=12)
    story = [
        Spacer(1, 28 * mm),
        Paragraph("PERSONALIZED TRAVEL ITINERARY", title),
        Paragraph(_safe_text(trip.title), title),
        Spacer(1, 8 * mm),
        Table(
            [[Paragraph(f"<b>{_safe_text(trip.itinerary.destination)}</b>", body)]],
            colWidths=[175 * mm],
            style=TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#0F766E")),
                ("TEXTCOLOR", (0, 0), (-1, -1), colors.white),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("BOX", (0, 0), (-1, -1), 8, colors.HexColor("#F97316")),
                ("TOPPADDING", (0, 0), (-1, -1), 12),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 12),
            ]),
        ),
        Spacer(1, 8 * mm),
        Paragraph(f"Travel party: {_safe_text(trip.preferences.party)} · "
                  f"{trip.preferences.travelers} traveler(s)", body),
        Paragraph(f"Duration: {trip.preferences.days} day(s) · "
                  f"Budget: {_safe_text(trip.preferences.budget_level)}", body),
        PageBreak(),
        Paragraph("Trip overview", heading),
        Paragraph(_safe_text(trip.itinerary.summary), body),
        Spacer(1, 5 * mm),
        Table(
            [["Currency", "Approximate total"],
             ["USD", f"${trip.itinerary.total_cost_usd:,.2f}"],
             ["INR", f"₹{trip.itinerary.total_cost_inr:,.0f}"],
             [_safe_text(trip.itinerary.currency_local), "See day-by-day costs"]],
            colWidths=[55 * mm, 120 * mm],
            style=TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#FEF3C7")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                ("FONTNAME", (0, 0), (-1, -1), font),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("PADDING", (0, 0), (-1, -1), 6),
            ]),
        ),
        Paragraph("Interests and preferences", heading),
        Paragraph(_safe_text(", ".join(trip.preferences.interests) or "Flexible exploration"), body),
    ]
    for day in trip.itinerary.days:
        story.extend([
            PageBreak(),
            Paragraph(f"Day {day.day_number}: {_safe_text(day.theme)}", heading),
            Paragraph(f"Area: {_safe_text(day.cluster_area)} · Transit: {day.transit_total_min} minutes", body),
        ])
        rows = [["Time", "Activity", "Area", "Cost", "Tips"]]
        for slot in day.slots:
            for activity in slot.activities:
                rows.append([
                    _safe_text(activity.start_time or slot.slot_type),
                    _safe_text(activity.name), _safe_text(activity.area),
                    f"{_safe_text(activity.currency_local)} {activity.cost_local:,.0f}",
                    _safe_text(activity.tips),
                ])
        story.append(Table(rows, repeatRows=1, colWidths=[25 * mm, 45 * mm, 32 * mm, 25 * mm, 48 * mm],
                           style=TableStyle([
                               ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F766E")),
                               ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                               ("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
                               ("FONTNAME", (0, 0), (-1, -1), font),
                               ("FONTSIZE", (0, 0), (-1, -1), 7),
                               ("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("PADDING", (0, 0), (-1, -1), 4),
                           ])))
        story.append(Paragraph(f"Day subtotal: ${day.day_total_usd:,.2f} · "
                               f"₹{day.day_total_inr:,.0f}", body))
    story.extend([
        PageBreak(),
        Paragraph("Packing & travel tips", heading),
        Paragraph("Pack comfortable shoes, weather-appropriate layers, medication, "
                  "a refillable bottle, and a portable charger. Download offline maps "
                  "before leaving reliable connectivity.", body),
        Paragraph("Emergency checklist", heading),
        Paragraph("□ Insurance details  □ Passport copy  □ Visa copy  □ Offline maps  "
                  "□ Emergency contacts  □ Embassy details", body),
        Paragraph(f"Police: {_safe_text(trip.itinerary.emergency_info.police)} · "
                  f"Ambulance: {_safe_text(trip.itinerary.emergency_info.ambulance)}", body),
        Paragraph(f"Tourist helpline: {_safe_text(trip.itinerary.emergency_info.tourist_helpline)}", body),
        Paragraph(f"Nearest hospital area: {_safe_text(trip.itinerary.emergency_info.nearest_hospital_area)}", body),
        Paragraph(_safe_text(trip.itinerary.emergency_info.embassy_note), body),
    ])
    document.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buffer.getvalue()
